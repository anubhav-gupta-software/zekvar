#!/bin/sh
set -eu

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 <<'SQL'
\getenv app_password ZEKVAR_POSTGRES_APP_PASSWORD
CREATE ROLE zekvar_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'app_password';
ALTER DATABASE zekvar OWNER TO zekvar_app;
REVOKE CONNECT ON DATABASE zekvar FROM PUBLIC;
SQL
