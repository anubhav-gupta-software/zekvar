// Renders docs/coverage.md from contracts/coverage/matrix.json.
// Usage: node scripts/coverage-doc.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const matrixUrl = new URL('contracts/coverage/matrix.json', root);
export const docUrl = new URL('docs/coverage.md', root);

const statusLabels = { supported: 'Supported', experimental: 'Experimental', unsupported: 'Unsupported' };
const modeLabels = { monitor: 'Monitor', warn: 'Warn', block: 'Block', redact: 'Redact' };
const fallbackLabels = { open: 'Fail open', closed: 'Fail closed' };
const controlLabels = { 'disable-attachments': 'Disable attachments', 'disable-adapter': 'Disable the whole adapter' };

function cellText(cell) {
  if (!cell || cell.status === 'unsupported') return 'Unsupported';
  return `${statusLabels[cell.status]} · v${cell.minBrowser}`;
}

function testLine({ file, name }) {
  return `- \`${file.replace(/^apps\//, '')}\`: ${name}`;
}

export function renderCoverage(matrix) {
  const lines = [];
  const push = (...values) => lines.push(...values);
  const evidenceTests = (kinds) => {
    const seen = new Map();
    for (const cell of [...matrix.cells, ...matrix.controls]) {
      for (const test of cell.tests) if (kinds.includes(test.evidence)) seen.set(`${test.file}\n${test.name}`, test);
    }
    return [...seen.values()].sort((a, b) => a.file.localeCompare(b.file) || a.name.localeCompare(b.name));
  };
  push('# App-by-action coverage', '',
    '<!-- Generated by scripts/coverage-doc.mjs from contracts/coverage/matrix.json. Do not edit by hand. -->', '',
    'This page lists what Zekvar Browser protects in each supported AI app, by user action and enforcement mode. ' +
    'The source of truth is `contracts/coverage/matrix.json`. A Browser test (`apps/browser-extension/test/coverage-matrix.test.mjs`) ' +
    'fails if a supported or experimental cell names a test that does not exist, or if this page is out of date.', '',
    '## Evidence status', '',
    '- **Controlled-fixture evidence** exists for every supported and experimental cell. Fixtures are local pages shaped like each app, ' +
    'served at the real app origin inside an isolated Chrome profile. They prove Browser behavior against the layouts the fixtures copy, ' +
    'not against the current production sites.',
    '- **Live signed-out evidence** is optional and limited to the public ChatGPT and Gemini pages. It runs only with ' +
    '`node scripts/verify-demo.mjs --live`, and its results are not recorded in this repository.',
    '- **Live signed-in evidence does not exist yet.** No cell has been verified in a signed-in customer workspace. ' +
    'Treat every cell as unverified on signed-in production layouts until that evidence is recorded.', '',
    '## Status definitions', '');
  for (const [status, text] of Object.entries(matrix.statuses)) push(`- **${statusLabels[status]}**: ${text}`);
  push('', 'Versions are the minimum Zekvar Browser release that ships the behavior. Modes that an action does not offer are Unsupported. ' +
    'File and intake actions offer Monitor and Block only. Redact is an employee action available when a prompt is warned or blocked.', '');

  push('## Summary', '', '| AI app | Supported | Experimental | Unsupported |', '| --- | --- | --- | --- |');
  for (const app of matrix.apps) {
    const cells = matrix.cells.filter((cell) => cell.app === app.id);
    const count = (status) => cells.filter((cell) => cell.status === status).length;
    push(`| ${app.name} | ${count('supported')} | ${count('experimental')} | ${count('unsupported')} |`);
  }
  push('');

  for (const app of matrix.apps) {
    push(`## ${app.name}`, '');
    if (app.note) push(app.note, '');
    push(`| Action | ${matrix.modes.map((mode) => modeLabels[mode]).join(' | ')} |`, `| --- | ${matrix.modes.map(() => '---').join(' | ')} |`);
    for (const action of matrix.actions) {
      const row = matrix.modes.map((mode) => cellText(matrix.cells.find((cell) => cell.app === app.id && cell.action === action.id && cell.mode === mode)));
      push(`| ${action.label} | ${row.join(' | ')} |`);
    }
    push('', `### ${app.name} evidence`, '');
    for (const action of matrix.actions) {
      const tests = new Map();
      for (const cell of matrix.cells.filter((entry) => entry.app === app.id && entry.action === action.id)) {
        for (const test of cell.tests) {
          const key = `${test.evidence}\n${test.file}\n${test.name}`;
          const entry = tests.get(key) ?? { ...test, modes: [] };
          entry.modes.push(modeLabels[cell.mode]);
          tests.set(key, entry);
        }
      }
      if (!tests.size) continue;
      push(`- ${action.label}:`);
      for (const test of tests.values()) {
        push(`  - ${matrix.evidenceLabels?.[test.evidence] ?? test.evidence} (${test.modes.join(', ')}): ${test.name}`);
      }
    }
    push('');
  }

  push('## Administrator adapter controls', '',
    'Control can disable one app adapter, or only its attachment intake, for the baseline or a rollout group. ' +
    'Browser reports a disabled adapter as **Disabled by administrator**, not Unsupported. Fail closed reuses the AI app access host block. ' +
    'See the broken-adapter runbook in `docs/support-and-incident-response.md`.', '',
    '| AI app | Control | Fallback | Status |', '| --- | --- | --- | --- |');
  for (const control of matrix.controls) {
    const app = matrix.apps.find(({ id }) => id === control.app);
    push(`| ${app.name} | ${controlLabels[control.control]} | ${fallbackLabels[control.fallback]} | ${cellText(control)} |`);
  }
  push('', '## Named tests', '', '### Controlled fixture, unit, and API tests', '');
  push(...evidenceTests(['fixture', 'unit', 'api']).map(testLine));
  push('', '### Live signed-out checks (optional)', '');
  push(...evidenceTests(['live-signed-out']).map(testLine));
  push('', '### Live signed-in checks', '', 'None yet.', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const matrix = JSON.parse(await readFile(matrixUrl, 'utf8'));
  const text = renderCoverage(matrix);
  if (process.argv.includes('--check')) {
    if (await readFile(docUrl, 'utf8').catch(() => '') !== text) {
      console.error('docs/coverage.md is out of date. Run node scripts/coverage-doc.mjs.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(docUrl, text);
  }
}
